/** The Lucide name a stored icon name stands for, old Tabler names included. */
export function iconName(stored: string): string {
  return TABLER_NAMES[stored] ?? stored;
}

/** The icon for a stored name; unknown names show as `server`. */
export function iconFor(stored: string): LucideIcon {
  return ICONS[iconName(stored)] ?? Server;
}
