export const ICON_NAMES = Object.keys(ICONS);

/**
 * Tabler's names, which services and domains stored before the icons moved
 * to Lucide, and the Lucide icon each now shows. Names both sets share
 * (server, database, cpu, key…) need no entry.
 */
