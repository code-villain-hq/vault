// Shared verification-gate helpers for every app's `scripts/check.ts`,
// and the domain → TypeScript binding regen every `gen-types.ts` runs.
import { readdir, rm } from "node:fs/promises";
import { $ } from "bun";

export type CheckStep = [string, () => Promise<unknown>];

/** Run each step in order; exit 1 on the first failure. */
export async function runChecks(steps: CheckStep[]): Promise<void> {
  for (const [name, run] of steps) {
    process.stdout.write(`• ${name}\n`);
    try {
      await run();
    } catch (error) {
      if (error instanceof Error && !("exitCode" in error)) console.error(error.message);
      console.error(`\n✗ ${name} failed`);
      process.exit(1);
    }
  }
  console.log("\n✓ all checks passed");
}

/** Snapshot of generated `.ts` files under `dir`, for drift checks. */
export async function typesSnapshot(dir: string): Promise<string> {
  const files = (await readdir(dir, { recursive: true }))
    .filter((f) => f.endsWith(".ts"))
    .sort();
  const contents = await Promise.all(files.map((f) => Bun.file(`${dir}/${f}`).text()));
  return JSON.stringify(files.map((f, i) => [f, contents[i]]));
}

/** Regenerate types and fail if `dir` changed (caller should commit the update). */
export async function assertTypesCurrent(
  dir: string,
  regenerate: () => Promise<unknown>,
): Promise<void> {
  const before = await typesSnapshot(dir);
  await regenerate();
  if (before !== (await typesSnapshot(dir))) {
    throw new Error(
      "packages/types was out of date; it has been regenerated, review and commit it",
    );
  }
}

/**
 * Regenerates `packages/types` from the Rust domain crate: ts-rs writes one
 * file per type, then this writes the index (plus the hand-written `sync.ts`).
 */
export async function genDomainTypes(root: string, domainPackage: string): Promise<void> {
  const generated = `${root}packages/types/src/generated`;
  await rm(generated, { recursive: true, force: true });
  await $`cargo test -p ${domainPackage} export_bindings --quiet`.cwd(root).quiet();
  const files = (await readdir(generated, { recursive: true }))
    .filter((file) => file.endsWith(".ts"))
    .map((file) => file.replace(/\.ts$/, ""))
    .sort();
  const index = [
    "// Generated by `bun run gen:types`. Do not edit.",
    ...files.map((file) => `export type * from "./generated/${file}";`),
    'export type * from "./sync";',
  ];
  await Bun.write(`${root}packages/types/src/index.ts`, `${index.join("\n")}\n`);
  console.log(`packages/types: ${files.length} types`);
}
